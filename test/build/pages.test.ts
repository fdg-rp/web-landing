// Every Markdown page in content/ is generated, with its title, description
// and share image. These are the checks most likely to catch a Nuxt, Nuxt
// Content or Docus upgrade that changes routing or the page head.

import { readFileSync } from "node:fs";
import { beforeAll, describe, expect, it } from "vitest";
import {
  assertBuildExists,
  builtFileFor,
  builtPage,
  contentPages,
  SITE_URL,
} from "../support/site";

const pages = contentPages();

beforeAll(assertBuildExists);

describe("content pages", () => {
  it("finds the content folder", () => {
    expect(pages.length).toBeGreaterThan(50);
  });

  it.each(pages.map((p) => [p.route, p] as const))("builds %s", (route, page) => {
    expect(builtFileFor(route), `${page.file} has no page at ${route}`).toBeDefined();

    const html = builtPage(route);
    expect(html.querySelector("html")?.getAttribute("lang")).toBe("en");

    const title = html.querySelector("title")?.text ?? "";
    expect(title).toMatch(/Fat Duck Gaming$/);
    if (page.title) expect(title).toContain(page.title);

    if (page.description) {
      const description = html
        .querySelector('meta[name="description"]')
        ?.getAttribute("content");
      expect(description).toBe(page.description);
    }

    // Each page has a share image. Docs pages get one generated by
    // nuxt-og-image (the file must exist and be a real PNG); the home page
    // uses the image set in app.config.ts.
    const ogImage = html.querySelector('meta[property="og:image"]')?.getAttribute("content");
    expect(ogImage, "og:image").toMatch(/^https:\/\//);
    if (route !== "/") {
      expect(ogImage!.startsWith(`${SITE_URL}/__og-image__/`)).toBe(true);
      const imageFile = builtFileFor(ogImage!.slice(SITE_URL.length));
      expect(imageFile, `${ogImage} was not generated`).toBeDefined();
      expect(readFileSync(imageFile!).subarray(1, 4).toString()).toBe("PNG");
    }

    // The page shows its own content, not an empty shell.
    expect(html.querySelector("main, #__nuxt")?.text.trim().length).toBeGreaterThan(0);
  });
});

describe("site-wide files", () => {
  it("serves a 404 page", () => {
    expect(builtFileFor("/404.html")).toBeDefined();
  });

  it("keeps the static files in public/", () => {
    for (const file of ["/favicon.ico", "/cover.png", "/img/fdg_logo.png"]) {
      expect(builtFileFor(file), file).toBeDefined();
    }
  });
});
